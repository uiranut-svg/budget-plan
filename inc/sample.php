/**
 * ใส่แหล่งเงินมาตรฐานให้ปี (เฉพาะเมื่อปีนั้นยังไม่มีแหล่งเงิน)
 * $scale = null → ยอดเป็น 0 (โครงสร้างอย่างเดียว) · ตัวเลข → ประมาณการตัวอย่าง × scale
 * $recvRatio = สัดส่วนรับจริงเทียบประมาณการ (ตัวอย่าง)
 */
function bp_seed_funds($yid, $scale = null, $recvRatio = 1.0)
{
    $yid = (int)$yid;
    $row = bp_row('SELECT COUNT(*) n FROM ' . bp_t('fund') . ' WHERE year_id=' . $yid);
    if ($row && (int)$row['n'] > 0) return 0;
    // ยอดยกมาตัวอย่าง (จาก vec.plan)
    $carry = array('ค่าจัดการเรียนการสอน' => 3210500, 'ค่าบำรุงการศึกษา' => 6845220.50, 'เงินบริจาค' => 125000);
    $n = 0;
    $k = 0;
    foreach (bp_seed_fund_tree() as $i => $f) {
        $own = isset($f[3]) ? $f[3] : 0;
        $vals = bp_seed_fund_vals($f[0], $own, $scale, $recvRatio, $carry, $k++);
        bp_query('INSERT INTO ' . bp_t('fund') . ' (year_id,parent_id,name,color,estimate,carry_in,received,sort) VALUES (' . $yid . ',NULL,' . q($f[0]) . ',' . q($f[1]) . ',' . $vals . ',' . $i . ')');
        $pid = bp_insert_id();
        $n++;
        $j = 0;
        foreach ($f[2] as $name => $est) {
            $vals = bp_seed_fund_vals($name, $est, $scale, $recvRatio, $carry, $k++);
            bp_query('INSERT INTO ' . bp_t('fund') . ' (year_id,parent_id,name,color,estimate,carry_in,received,sort) VALUES (' . $yid . ',' . $pid . ',' . q($name) . ",''," . $vals . ',' . ($j++) . ')');
            $n++;
        }
    }
    return $n;
}
function bp_seed_fund_vals($name, $est, $scale, $recvRatio, $carry, $k)
{
    if ($scale === null) return '0,0,0';
    $e = round($est * $scale / 1000) * 1000;
    $c = isset($carry[$name]) ? round($carry[$name] * $scale, 2) : 0;
    // รับจริงแกว่ง ±3% ให้ดูเป็นตัวเลขจริง
    $wob = array(1.0, 0.985, 1.012, 0.97, 1.0, 0.994, 1.021, 0.96, 1.0, 1.008);
    $r = round($e * $recvRatio * $wob[$k % count($wob)], 2);
    return $e . ',' . $c . ',' . $r;
}

